-- =====================================================================
--  体幹教室 回数管理：繰越（既消費回数）オフセット
-- ---------------------------------------------------------------------
--  前システム／前月から跨いで通っている会員は、システム導入前に
--  既に何回か消費している。その回数を prior_count に入れておくと、
--   ・回数管理表の「何回目」がその分ずれて表示される（例：6回目〜）
--   ・終了通知（LINE）の「今月◯回目／残り◯回」もずれて正しくなる
--  月ごと（name, ym）に持たせる。移行月だけ入れれば翌月は0でよい。
--
--  Supabase の SQL Editor で1回実行（再実行しても安全）。
-- =====================================================================
alter table public.class_purchases
  add column if not exists prior_count int not null default 0;
