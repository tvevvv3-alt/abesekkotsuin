// アプリに入っているレシピ集。献立の提案はここから選ぶ（AI を使わないので費用はかからない）。
// ing は主な食材だけ（調味料は書かない）。名前は ingredients.ts の辞書に揃える。
// toddler は三男（1歳半前後）向けの取り分け・調整方法。

export type RecipeSlot = "breakfast" | "bento" | "dinner" | "soup" | "side";
export type Protein = "meat" | "fish" | "egg" | "soy" | "veg";

export type Recipe = {
  id: string;
  slot: RecipeSlot;
  name: string;
  sides: string[]; // 朝食・お弁当の添え物（夕食は汁物・副菜を自動で組み合わせる）
  rice: boolean; // お米を食べる献立か
  riceDish: boolean; // 丼・カレーなど、ご飯と一体の料理（夕食で別に「ご飯」を付けない）
  noodle: boolean; // 麺・パン・パスタなど、お米を食べない主食
  protein: Protein;
  ing: string[];
  min: number; // 作る時間の目安（分）
  toddler: string;
  custom?: boolean; // 家族が追加した料理
};

type Opt = Partial<Pick<Recipe, "riceDish" | "noodle" | "protein">>;

const base = (slot: RecipeSlot, id: string, name: string, ing: string[], min: number, toddler: string, o: Opt = {}): Recipe => ({
  id,
  slot,
  name,
  sides: [],
  rice: !o.noodle,
  riceDish: !!o.riceDish,
  noodle: !!o.noodle,
  protein: o.protein ?? "meat",
  ing,
  min,
  toddler,
});

// 夕食の主菜
const D = (id: string, name: string, protein: Protein, ing: string[], min: number, toddler: string, o: Opt = {}) =>
  base("dinner", id, name, ing, min, toddler, { protein, ...o });

// 朝食（添え物つきのセット）
const B = (id: string, name: string, sides: string[], protein: Protein, ing: string[], min: number, toddler: string, o: Opt = {}) => ({
  ...base("breakfast", id, name, ing, min, toddler, { protein, ...o }),
  sides,
});

// お弁当（長男・次男）
const L = (id: string, name: string, sides: string[], protein: Protein, ing: string[], min: number, o: Opt = {}) => ({
  ...base("bento", id, name, ing, min, "", { protein, ...o }),
  sides,
});

const S = (id: string, name: string, ing: string[]) => base("soup", id, name, ing, 10, "", { protein: "veg" });
const V = (id: string, name: string, ing: string[]) => base("side", id, name, ing, 10, "", { protein: "veg" });

