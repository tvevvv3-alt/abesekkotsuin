// ひらがな・カタカナの違いをなくし、全角/半角を揃える
export function normalizeText(s: string): string {
  return s
    .normalize("NFKC")
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .toLowerCase();
}

const INDEX = INGREDIENTS.flatMap((e) => e.aliases.map((a) => ({ key: normalizeText(a), entry: e }))).sort(
  (a, b) => b.key.length - a.key.length
);

// 文字列の中に含まれる食材を探す（長い書き方を優先）
export function findIngredient(text: string): Entry | null {
  const t = normalizeText(text);
  return INDEX.find((i) => t.includes(i.key))?.entry ?? null;
}

export function ingredientInfo(name: string): Entry | null {
  return INGREDIENTS.find((e) => e.name === name) ?? findIngredient(name);
}

// 在庫の名前（自由入力）とレシピの食材名が同じものか
export function sameIngredient(pantryName: string, recipeIngredient: string): boolean {
  const a = ingredientInfo(pantryName)?.name ?? normalizeText(pantryName);
  const b = ingredientInfo(recipeIngredient)?.name ?? normalizeText(recipeIngredient);
  return a === b;
}
